#!/usr/bin/env python3
"""Repair a yum channel's repodata so it matches the RPM actually served.

Why this exists
---------------
Publishing is incremental: the workflow pulls the channel's current repodata,
slots the new .rpm into the local channel dir, builds a throwaway single-package
repo, and merges the two with `mergerepo_c --all`. `--all` is what preserves
historical versions without their .rpm files being present locally.

The sharp edge is a *re-cut*: when a version is re-released under the same
version number, the channel already carries a primary.xml record for that
version-arch, and the merge can keep the OLD record (the previous build's
checksum and size) rather than the one for the .rpm we just published. The pool
object is then replaced with the new build, so the metadata advertises a file
that no longer exists. dnf downloads the served .rpm, fails validation and
reports:

    >>> Downloading successful, but checksum doesn't match.
    Failed to download packages
     Librepo error: Cannot download packages/wheels-X.Y.Z.noarch.rpm: All
     mirrors were tried

...which is a hard install failure for every consumer of that channel, on a
repository that otherwise looks healthy (repomd.xml is signed, the .rpm is
present and downloadable by hand).

What this does
--------------
Rewrites the primary/filelists/other payloads with the correct checksum and
size for the RPM just published, updates repomd.xml in place, and drops the
sqlite caches. The caches cannot be regenerated byte-exactly without the full
RPM pool (createrepo_c --update would DROP records for the historical .rpm
files that are not on disk), and leaving a stale *_db in repomd.xml would
shadow the corrected XML for dnf clients. dnf falls back to the XML indexes
when no *_db component is advertised, which is the same path it uses for any
repository published without --database.

Idempotent: re-running over already-correct metadata rewrites identical bytes
(gzip mtime is pinned to 0).

Usage:
    repair-repodata.py <repo-dir> <rpm-basename> <sha256> <size-bytes>

<repo-dir> is the channel directory containing repodata/ (e.g. "stable").
"""
import sys
import os
import gzip
import hashlib
import re

import createrepo_c as cr


def _version_key(version):
    """Sort key so 4.10.0 sorts above 4.9.0 (plain strings would invert that)."""
    parts = []
    for chunk in re.split(r"[.\-~+]", version):
        parts.append((0, int(chunk), "") if chunk.isdigit() else (1, 0, chunk))
    return parts


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__.strip().splitlines()[-2].strip())

    repo, pkgfile, newsum, newsize = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
    repomd_path = os.path.join(repo, "repodata", "repomd.xml")
    if not os.path.isfile(repomd_path):
        sys.exit(f"ERROR: {repomd_path} not found — nothing to repair.")

    repomd = open(repomd_path, encoding="utf-8").read()
    hrefs = re.findall(r'href="([^"]+)"', repomd)

    md = cr.Metadata()
    # ignore_db=True: we only need the XML indexes; the *_db caches are dropped.
    md.load_xml(cr.MetadataLocation(repo, True))

    # Locate the record for the RPM we just published by its location href.
    target = None
    for key in md.keys():
        pkg = md.get(key)
        if (pkg.location_href or "").endswith(pkgfile):
            target = pkg
            break
    if target is None:
        sys.exit(f"ERROR: no repodata record matched {pkgfile}")

    print(
        f"  {target.name}-{target.version}.{target.arch}: "
        f"pkgId {target.pkgId[:12]} -> {newsum[:12]}, "
        f"size {target.size_package} -> {newsize}"
    )
    # pkgId is the package checksum; repodata keys are checksums.
    target.pkgId = newsum
    target.size_package = newsize

    # Sort deterministically. The load order of primary/filelists/other is not
    # guaranteed stable across runs, and an unstable order would reshuffle the
    # rewritten payloads (and therefore their checksums) on every publish even
    # when nothing changed. Sorting also makes re-runs byte-identical.
    packages = sorted(
        (md.get(k) for k in md.keys()),
        key=lambda p: (
            p.name or "",
            _version_key(p.version or ""),
            p.arch or "",
            p.pkgId or "",
        ),
    )
    print(f"  rewriting {len(packages)} package records")

    def write_xml(kind, dumper, href):
        ns, root = {
            "primary": ("http://linux.duke.edu/metadata/common", "metadata"),
            "filelists": ("http://linux.duke.edu/metadata/filelists", "filelists"),
            "other": ("http://linux.duke.edu/metadata/other", "otherdata"),
        }[kind]
        head = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<{root} xmlns="{ns}" '
            'xmlns:rpm="http://linux.duke.edu/metadata/rpm" '
            f'packages="{len(packages)}">\n'
        )
        body = "".join(dumper(p) for p in packages)
        raw = (head + body + f"</{root}>\n").encode("utf-8")
        # mtime=0 keeps the gzip output byte-stable across runs.
        data = gzip.compress(raw, 9, mtime=0)
        with open(os.path.join(repo, href), "wb") as handle:
            handle.write(data)
        print(f"  wrote {kind}: {len(packages)} records ({len(data)} bytes gz)")
        return hashlib.sha256(data).hexdigest(), len(data)

    rewritten = {}
    for kind, dumper in (
        ("primary", cr.xml_dump_primary),
        ("filelists", cr.xml_dump_filelists),
        ("other", cr.xml_dump_other),
    ):
        href = next((h for h in hrefs if re.search(rf"-{kind}\.xml(\.gz)?$", h)), None)
        if href is None:
            continue
        rewritten[kind] = (href,) + write_xml(kind, dumper, href)

    # Update the checksum + size of each rewritten component in repomd.xml.
    def patch_component(xml, href, sha, size):
        pattern = re.compile(
            r'(<checksum type="sha256">)[a-f0-9]+(</checksum>\s*'
            r'<open-checksum type="sha256">[a-f0-9]+</open-checksum>\s*'
            r'<location href="' + re.escape(href) + r'"/>\s*'
            r'<timestamp>\d+</timestamp>\s*<size>)\d+(</size>)',
            re.S,
        )
        out, count = pattern.subn(
            lambda m: m.group(1) + sha + m.group(2) + str(size) + m.group(3), xml
        )
        if count != 1:
            sys.exit(f"ERROR: expected exactly 1 repomd match for {href}, got {count}")
        return out

    for href, sha, size in rewritten.values():
        repomd = patch_component(repomd, href, sha, size)

    # Drop the (*now stale*) sqlite caches so dnf reads the corrected XML.
    for kind in ("primary_db", "filelists_db", "other_db"):
        pattern = re.compile(r'\n?\s*<data type="' + kind + r'">.*?</data>', re.S)
        repomd, count = pattern.subn("", repomd)
        if count:
            print(f"  dropped {kind} component (dnf falls back to the XML index)")
    for href in hrefs:
        if ".sqlite" in href:
            stale_cache = os.path.join(repo, href)
            if os.path.exists(stale_cache):
                os.remove(stale_cache)

    with open(repomd_path, "w", encoding="utf-8") as handle:
        handle.write(repomd)
    print("  repomd.xml updated")


if __name__ == "__main__":
    main()
